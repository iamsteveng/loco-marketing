// Generates public/student/schools.js from school-domains.csv.
// Usage: node data/school-domains/build.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const csvPath = join(here, "school-domains.csv");
const outPath = join(here, "..", "..", "public", "student", "schools.js");

function parseCsv(text) {
  const rows = [];
  let row = [];
  let field = "";
  let quoted = false;
  for (let i = 0; i < text.length; i++) {
    const c = text[i];
    if (quoted) {
      if (c === '"' && text[i + 1] === '"') { field += '"'; i++; }
      else if (c === '"') quoted = false;
      else field += c;
    } else if (c === '"') quoted = true;
    else if (c === ",") { row.push(field); field = ""; }
    else if (c === "\n" || c === "\r") {
      if (c === "\r" && text[i + 1] === "\n") i++;
      row.push(field); rows.push(row); row = []; field = "";
    } else field += c;
  }
  if (field || row.length) { row.push(field); rows.push(row); }
  return rows.filter((r) => r.some((f) => f.trim()));
}

const [header, ...body] = parseCsv(readFileSync(csvPath, "utf8").replace(/^﻿/, ""));
if (header.length !== 3) throw new Error(`Expected 3 columns, got: ${header.join(",")}`);

// One Eligible School per (English name, Chinese name); a school may have several domains.
const schools = new Map();
const seenDomains = new Set();
for (const [i, cells] of body.entries()) {
  const [en, zh, domain] = cells.map((c) => c.trim());
  const line = i + 2;
  if (!en || !zh || !domain) throw new Error(`Line ${line}: empty field`);
  if (domain.includes("@") || domain.includes(" ")) throw new Error(`Line ${line}: bad domain "${domain}"`);
  const d = domain.toLowerCase();
  if (seenDomains.has(d)) throw new Error(`Line ${line}: duplicate domain "${d}"`);
  seenDomains.add(d);
  const key = `${en}\u0000${zh}`;
  if (!schools.has(key)) schools.set(key, { en, zh, domains: [] });
  schools.get(key).domains.push(d);
}

const list = [...schools.values()].sort((a, b) => a.en.localeCompare(b.en, "en"));
const js =
  "// Generated by data/school-domains/build.mjs. Do not edit by hand.\n" +
  `window.SCHOOLS = ${JSON.stringify(list, null, 0).replace(/\},\{/g, "},\n{")};\n`;
writeFileSync(outPath, js);
console.log(`Wrote ${list.length} schools (${seenDomains.size} domains) to ${outPath}`);
